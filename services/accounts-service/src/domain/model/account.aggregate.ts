/**
 * @file Defines the AccountAggregate, the core of the accounts domain.
 * This file implements the DDD Aggregate pattern for the Account entity,
 * using Event Sourcing to manage its state.
 */

import { v4 as uuidv4 } from 'uuid';
import {
  AccountCreatedEvent,
  FundsDepositedEvent,
  FundsWithdrawnEvent,
  AccountFrozenEvent,
  AccountUnfrozenEvent,
  AccountClosedEvent,
  IDomainEvent,
} from '../events'; // Assuming events are defined in a central index file under ../events

/**
 * Represents the possible statuses of an account.
 * @enum {string}
 */
export enum AccountStatus {
  OPEN = 'OPEN',
  FROZEN = 'FROZEN',
  CLOSED = 'CLOSED',
}

/**
 * @class AccountAggregate
 * @implements DDD Aggregate Root pattern
 * @description This is the aggregate root for the Account domain. It encapsulates the state and business logic
 * for an account. State changes are not performed directly but by creating and applying domain events.
 * This ensures a complete, auditable history of every change (Event Sourcing).
 */
export class AccountAggregate {
  /**
   * The unique identifier for the account aggregate.
   * @public
   * @readonly
   */
  public readonly id!: string;

  /**
   * The ID of the user who owns this account.
   * @private
   */
  private ownerId!: string;

  /**
   * The current balance of the account.
   * @private
   */
  private balance: number = 0;

  /**
   * The current status of the account.
   * @private
   */
  private status!: AccountStatus;

  /**
   * The current version of the aggregate, incremented with each event.
   * Used for optimistic concurrency control.
   * @private
   */
  private version: number = -1;

  /**
   * A list of events that have been generated by business operations but not yet persisted.
   * @private
   */
  private _uncommittedEvents: IDomainEvent[] = [];

  /**
   * Private constructor to enforce aggregate creation via factory methods.
   * This prevents creating an aggregate instance without an initial event, which is a core concept in Event Sourcing.
   * @private
   */
  private constructor() {}

  /**
   * Retrieves the list of uncommitted domain events.
   * The event store or repository is responsible for persisting these events and then clearing them from the aggregate.
   * @returns {IDomainEvent[]} An array of domain events that need to be persisted.
   */
  public get uncommittedEvents(): IDomainEvent[] {
    return this._uncommittedEvents;
  }

  /**
   * Clears the list of uncommitted events. This should be called by the repository
   * after the events have been successfully persisted to the event store.
   */
  public markEventsAsCommitted(): void {
    this._uncommittedEvents = [];
  }

  /**
   * Factory method to create a new Account. This is the designated public entry point for instantiating a new account.
   * It ensures the aggregate is created in a valid state by applying the initial `AccountCreatedEvent`.
   * @param {string} ownerId - The ID of the customer owning the account.
   * @param {number} [initialBalance=0] - The starting balance for the account. Defaults to 0.
   * @returns {AccountAggregate} The newly created account aggregate instance with the creation event ready to be committed.
   * @throws {Error} if the initial balance is negative.
   * @static
   */
  public static create(ownerId: string, initialBalance: number = 0): AccountAggregate {
    if (initialBalance < 0) {
      throw new Error('Initial balance cannot be negative.');
    }
    const account = new AccountAggregate();
    const id = uuidv4();
    account.apply(new AccountCreatedEvent(id, { ownerId, initialBalance }), true);
    return account;
  }

  /**
   * Reconstitutes an Account aggregate from a history of its domain events.
   * This method is used by the repository to load an existing aggregate from the event store.
   * @param {string} id - The aggregate's unique identifier.
   * @param {IDomainEvent[]} history - An ordered array of domain events representing the aggregate's history.
   * @returns {AccountAggregate} The reconstituted account aggregate instance in its current state.
   * @static
   */
  public static loadFromHistory(id: string, history: IDomainEvent[]): AccountAggregate {
    const account = new AccountAggregate();
    (account as any).id = id; // Set id directly as we are loading from history
    history.forEach(event => account.apply(event, false));
    account.version = history.length - 1;
    return account;
  }

  /**
   * Deposits a specified amount of funds into the account.
   * @param {number} amount - The amount to deposit. Must be a positive number.
   * @throws {Error} if the account is closed or frozen, as these states restrict transactions.
   * @throws {Error} if the deposit amount is not a positive number.
   */
  public deposit(amount: number): void {
    if (this.status === AccountStatus.CLOSED) {
      throw new Error('Cannot deposit funds into a closed account.');
    }
    if (this.status === AccountStatus.FROZEN) {
      throw new Error('Cannot deposit funds into a frozen account.');
    }
    if (amount <= 0) {
      throw new Error('Deposit amount must be positive.');
    }
    this.apply(new FundsDepositedEvent(this.id, { amount }), true);
  }

  /**
   * Withdraws a specified amount of funds from the account.
   * @param {number} amount - The amount to withdraw. Must be a positive number.
   * @throws {Error} if the account is closed or frozen.
   * @throws {Error} if the withdrawal amount is greater than the current balance (insufficient funds).
   * @throws {Error} if the withdrawal amount is not a positive number.
   */
  public withdraw(amount: number): void {
    if (this.status === AccountStatus.CLOSED) {
      throw new Error('Cannot withdraw funds from a closed account.');
    }
    if (this.status === AccountStatus.FROZEN) {
      throw new Error('Cannot withdraw funds from a frozen account.');
    }
    if (amount <= 0) {
      throw new Error('Withdrawal amount must be positive.');
    }
    if (this.balance < amount) {
      throw new Error('Insufficient funds for withdrawal.');
    }
    this.apply(new FundsWithdrawnEvent(this.id, { amount }), true);
  }

  /**
   * Freezes the account, preventing deposits and withdrawals.
   * @throws {Error} if the account is already closed or frozen.
   */
  public freeze(): void {
    if (this.status === AccountStatus.CLOSED) {
      throw new Error('Cannot freeze a closed account.');
    }
    if (this.status === AccountStatus.FROZEN) {
      throw new Error('Account is already frozen.');
    }
    this.apply(new AccountFrozenEvent(this.id, {}), true);
  }

  /**
   * Unfreezes the account, re-enabling deposits and withdrawals.
   * @throws {Error} if the account is not currently frozen.
   */
  public unfreeze(): void {
    if (this.status !== AccountStatus.FROZEN) {
      throw new Error('Account is not frozen.');
    }
    this.apply(new AccountUnfrozenEvent(this.id, {}), true);
  }

  /**
   * Closes the account. This is a final, irreversible action.
   * @throws {Error} if the account balance is not zero, to prevent loss of funds.
   * @throws {Error} if the account is already closed.
   */
  public close(): void {
    if (this.balance !== 0) {
      throw new Error('Cannot close an account with a non-zero balance.');
    }
    if (this.status === AccountStatus.CLOSED) {
      throw new Error('Account is already closed.');
    }
    this.apply(new AccountClosedEvent(this.id, {}), true);
  }

  /**
   * The core state mutation logic. It routes an event to the appropriate `on` method
   * to apply state changes and adds new events to the uncommitted list.
   * @param {IDomainEvent} event - The domain event to apply.
   * @param {boolean} isNew - Flag indicating if this is a new event (to be committed) or one from history (already committed).
   * @private
   */
  private apply(event: IDomainEvent, isNew: boolean): void {
    // This is a simple routing mechanism. A more robust implementation might use decorators or a map.
    switch (event.eventType) {
      case 'AccountCreatedEvent':
        this.onAccountCreated(event as AccountCreatedEvent);
        break;
      case 'FundsDepositedEvent':
        this.onFundsDeposited(event as FundsDepositedEvent);
        break;
      case 'FundsWithdrawnEvent':
        this.onFundsWithdrawn(event as FundsWithdrawnEvent);
        break;
      case 'AccountFrozenEvent':
        this.onAccountFrozen(event as AccountFrozenEvent);
        break;
      case 'AccountUnfrozenEvent':
        this.onAccountUnfrozen(event as AccountUnfrozenEvent);
        break;
      case 'AccountClosedEvent':
        this.onAccountClosed(event as AccountClosedEvent);
        break;
      default:
        throw new Error(`Unknown event type: ${event.eventType}`);
    }

    if (isNew) {
      this._uncommittedEvents.push(event);
    }
  }

  /**
   * State mutator for the AccountCreatedEvent. Initializes the aggregate's state.
   * @param {AccountCreatedEvent} event - The event data.
   * @private
   */
  private onAccountCreated(event: AccountCreatedEvent): void {
    // Cast 'this' to any to set the readonly 'id' property on instantiation
    (this as any).id = event.aggregateId;
    this.ownerId = event.payload.ownerId;
    this.balance = event.payload.initialBalance;
    this.status = AccountStatus.OPEN;
  }

  /**
   * State mutator for the FundsDepositedEvent. Increases the account balance.
   * @param {FundsDepositedEvent} event - The event data.
   * @private
   */
  private onFundsDeposited(event: FundsDepositedEvent): void {
    this.balance += event.payload.amount;
  }

  /**
   * State mutator for the FundsWithdrawnEvent. Decreases the account balance.
   * @param {FundsWithdrawnEvent} event - The event data.
   * @private
   */
  private onFundsWithdrawn(event: FundsWithdrawnEvent): void {
    this.balance -= event.payload.amount;
  }

  /**
   * State mutator for the AccountFrozenEvent. Sets the account status to FROZEN.
   * @param {AccountFrozenEvent} event - The event data.
   * @private
   */
  private onAccountFrozen(event: AccountFrozenEvent): void {
    this.status = AccountStatus.FROZEN;
  }

  /**
   * State mutator for the AccountUnfrozenEvent. Sets the account status back to OPEN.
   * @param {AccountUnfrozenEvent} event - The event data.
   * @private
   */
  private onAccountUnfrozen(event: AccountUnfrozenEvent): void {
    this.status = AccountStatus.OPEN;
  }

  /**
   * State mutator for the AccountClosedEvent. Sets the account status to CLOSED.
   * @param {AccountClosedEvent} event - The event data.
   * @private
   */
  private onAccountClosed(event: AccountClosedEvent): void {
    this.status = AccountStatus.CLOSED;
  }
}
