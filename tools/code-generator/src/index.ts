/**
 * @file Main entry point for the Elite AI Implementation Team's in-house code generation framework.
 * @version 1.0.0
 * @description This tool consumes OpenAPI v3 specifications and generates code for various targets,
 * adhering to the principles of Hexagonal Architecture.
 * It is designed to be extensible to support multiple languages and frameworks.
 * Comprehensive TSDoc is mandatory for all generated artifacts.
 */

import { Command } from 'commander';
import * as path from 'path';
import * as fs from 'fs-extra';
import SwaggerParser from '@apidevtools/swagger-parser';
import { OpenAPI, OpenAPIV3 } from 'openapi-types';
import * as Handlebars from 'handlebars';
import { pascalCase, capitalCase } from 'change-case';

/**
 * Defines the contract for a code generator.
 * Each generator is responsible for creating a set of files for a specific target (e.g., typescript-server).
 */
interface ICodeGenerator {
  /**
   * Generates code from a given OpenAPI specification and writes it to an output directory.
   *
   * @param {OpenAPI.Document} spec - The parsed OpenAPI specification document.
   * @param {string} outputDir - The root directory where generated files should be written.
   * @returns {Promise<void>} A promise that resolves when the generation is complete.
   */
  generate(spec: OpenAPI.Document, outputDir: string): Promise<void>;
}

// --- TypeScript Server Generator ---

/**
 * Generates server-side code for a TypeScript/Node.js microservice using Express.
 * It creates DTOs, Port interfaces, and Express route stubs, enforcing a Hexagonal Architecture.
 */
class TypeScriptServerGenerator implements ICodeGenerator {
  private readonly dtoTemplate: Handlebars.TemplateDelegate;
  private readonly portsTemplate: Handlebars.TemplateDelegate;
  private readonly routesTemplate: Handlebars.TemplateDelegate;

  /**
   * Initializes the generator and compiles the Handlebars templates.
   */
  constructor() {
    this.dtoTemplate = Handlebars.compile(`/**
 * @file Auto-generated by code-generator.
 * @version {{spec.info.version}}
 * @description Data Transfer Objects (DTOs) for the {{spec.info.title}} service.
 */

/* eslint-disable */

{{#each schemas}}
/**
 * TSDoc for {{this.name}}
 * {{this.description}}
 */
export interface {{this.name}} {
  {{#each this.properties}}
  /**
   * {{this.description}}
   * @example {{{this.example}}}
   */
  readonly {{this.name}}{{this.requiredChar}}: {{this.type}};
  {{/each}}
}
{{/each}}
`);

    this.portsTemplate = Handlebars.compile(`/**
 * @file Auto-generated by code-generator.
 * @version {{spec.info.version}}
 * @description Port interfaces for the core domain logic of the {{spec.info.title}} service.
 */

import { {{dtoImports}} } from './dtos';

/* eslint-disable */

{{#each operations}}
/**
 * Interface for the {{this.capitalizedName}} port.
 * {{this.description}}
 */
export interface I{{this.pascalName}}Port {
  /**
   * Executes the {{this.name}} operation.
   * @param { {{this.paramType}} } params - The input parameters for the operation.
   * @returns {Promise<{{this.responseType}}>} A promise that resolves with the operation's result.
   */
  execute(params: {{this.paramType}}): Promise<{{this.responseType}}>;
}
{{/each}}
`);

    this.routesTemplate = Handlebars.compile(`/**
 * @file Auto-generated by code-generator.
 * @version {{spec.info.version}}
 * @description Express router for the {{spec.info.title}} service.
 */

import { Router, Request, Response, NextFunction } from 'express';
import { {{dtoImports}} } from '../domain/dtos';
// TODO: Import port implementations from the adapters layer.

/* eslint-disable */

const router = Router();

{{#each routes}}
/**
 * {{this.method}} {{this.path}}
 * {{this.summary}}
 * {{this.description}}
 */
router.{{this.method}}('{{this.expressPath}}', async (req: Request, res: Response, next: NextFunction) => {
  try {
    // TODO: Instantiate and call the appropriate port implementation.
    // const result = await somePort.execute({ body: req.body, params: req.params });
    console.log('Handling request for operationId: {{this.operationId}}');
    res.status(501).json({ message: 'Not Implemented' });
  } catch (error) {
    next(error);
  }
});
{{/each}}

export default router;
`);
  }

  /**
   * @inheritdoc
   */
  public async generate(spec: OpenAPI.Document, outputDir: string): Promise<void> {
    if (spec.openapi < '3.0.0') {
      throw new Error('This generator only supports OpenAPI 3.0.0 and above.');
    }
    const specV3 = spec as OpenAPIV3.Document;

    const domainDir = path.join(outputDir, 'domain');
    const apiDir = path.join(outputDir, 'api');
    await fs.ensureDir(domainDir);
    await fs.ensureDir(apiDir);

    await this.generateDtos(specV3, domainDir);
    await this.generatePorts(specV3, domainDir);
    await this.generateRoutes(specV3, apiDir);
  }

  private toTsType(schema: OpenAPIV3.SchemaObject | OpenAPIV3.ReferenceObject | undefined): string {
    if (!schema) return 'any';
    if ('$ref' in schema) {
      return pascalCase(schema.$ref.split('/').pop() || 'any');
    }
    switch (schema.type) {
      case 'string':
        return 'string';
      case 'number':
      case 'integer':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'array':
        return `${this.toTsType(schema.items)}[]`;
      case 'object':
        return 'Record<string, any>'; // Simplified for this example
      default:
        return 'any';
    }
  }

  private async generateDtos(spec: OpenAPIV3.Document, outDir: string): Promise<void> {
    const schemas = [];
    if (spec.components?.schemas) {
      for (const schemaName in spec.components.schemas) {
        const schemaObject = spec.components.schemas[schemaName] as OpenAPIV3.SchemaObject;
        const properties = [];
        if (schemaObject.properties) {
          for (const propName in schemaObject.properties) {
            const propSchema = schemaObject.properties[propName] as OpenAPIV3.SchemaObject;
            properties.push({
              name: propName,
              description: propSchema.description || 'No description.',
              requiredChar: schemaObject.required?.includes(propName) ? '' : '?',
              type: this.toTsType(propSchema),
              example: JSON.stringify(propSchema.example) || 'undefined',
            });
          }
        }
        schemas.push({
          name: pascalCase(schemaName),
          description: schemaObject.description || 'No description.',
          properties,
        });
      }
    }

    const content = this.dtoTemplate({ schemas, spec });
    await fs.writeFile(path.join(outDir, 'dtos.ts'), content);
    console.log(`Generated domain/dtos.ts`);
  }

  private async generatePorts(spec: OpenAPIV3.Document, outDir: string): Promise<void> {
    const operations: any[] = [];
    const dtoNames = new Set<string>();

    for (const p in spec.paths) {
        const pathItem = spec.paths[p]!;
        for (const method in pathItem) {
            if (['get', 'post', 'put', 'delete', 'patch'].includes(method)) {
                const op = pathItem[method as OpenAPIV3.HttpMethods] as OpenAPIV3.OperationObject;
                if (op.operationId) {
                    let responseType = 'void';
                    // Find first successful response (2xx)
                    const successResponseKey = Object.keys(op.responses).find(k => k.startsWith('2'));
                    if (successResponseKey) {
                        const successResponse = op.responses[successResponseKey] as OpenAPIV3.ResponseObject;
                        if (successResponse.content?.['application/json']?.schema) {
                            responseType = this.toTsType(successResponse.content['application/json'].schema);
                            if (!['string', 'number', 'boolean', 'any', 'void'].includes(responseType) && !responseType.endsWith('[]')) {
                                dtoNames.add(responseType);
                            }
                        }
                    }

                    let paramType = '{ [key: string]: any }'; // Generic for now
                    if (op.requestBody && 'content' in op.requestBody) {
                        const requestBodyType = this.toTsType(op.requestBody.content['application/json']?.schema);
                        paramType = `{ body: ${requestBodyType} }`;
                        if (!['string', 'number', 'boolean', 'any', 'void'].includes(requestBodyType) && !requestBodyType.endsWith('[]')) {
                            dtoNames.add(requestBodyType);
                        }
                    }

                    operations.push({
                        name: op.operationId,
                        pascalName: pascalCase(op.operationId),
                        capitalizedName: capitalCase(op.operationId),
                        description: op.description || op.summary || 'No description.',
                        responseType,
                        paramType,
                    });
                }
            }
        }
    }

    const content = this.portsTemplate({ operations, spec, dtoImports: Array.from(dtoNames).join(', ') });
    await fs.writeFile(path.join(outDir, 'ports.ts'), content);
    console.log(`Generated domain/ports.ts`);
  }

  private async generateRoutes(spec: OpenAPIV3.Document, outDir: string): Promise<void> {
    const routes: any[] = [];
    const dtoNames = new Set<string>();

    for (const p in spec.paths) {
      const pathItem = spec.paths[p]!;
      for (const method in pathItem) {
        if (['get', 'post', 'put', 'delete', 'patch'].includes(method)) {
          const op = pathItem[method as OpenAPIV3.HttpMethods] as OpenAPIV3.OperationObject;
          routes.push({
            path: p,
            expressPath: p.replace(/{/g, ':').replace(/}/g, ''),
            method: method.toLowerCase(),
            operationId: op.operationId || 'unknownOperation',
            summary: op.summary || '',
            description: op.description || '',
          });
        }
      }
    }

    const content = this.routesTemplate({ routes, spec, dtoImports: Array.from(dtoNames).join(', ') });
    await fs.writeFile(path.join(outDir, 'routes.ts'), content);
    console.log(`Generated api/routes.ts`);
  }
}

