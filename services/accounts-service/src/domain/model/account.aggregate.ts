/**
 * @file Defines the AccountAggregate, the core of the accounts domain.
 * @description This file implements the DDD Aggregate pattern for the Account entity,
 * using Event Sourcing to manage its state. It follows modern CQRS principles,
 * where state changes are captured as a sequence of immutable domain events.
 * @version 2.0.0
 * @author Elite AI Implementation Team
 */

import { v4 as uuidv4 } from 'uuid';
import {
  AccountClosedEvent,
  AccountCreatedEvent,
  AccountFrozenEvent,
  AccountUnfrozenEvent,
  FundsDepositedEvent,
  FundsWithdrawnEvent,
  IDomainEvent,
} from '../events';
import { DomainError, ValidationError } from '../../../../../libs/error-framework/src';

/**
 * @enum {string} AccountStatus
 * @description Represents the possible lifecycle statuses of a financial account.
 * @property {string} PENDING - The account is pending creation and not yet active.
 * @property {string} OPEN - The account is open and active for transactions.
 * @property {string} FROZEN - The account is frozen; transactions are temporarily blocked.
 * @property {string} CLOSED - The account is permanently closed and cannot be used.
 */
export enum AccountStatus {
  PENDING = 'PENDING',
  OPEN = 'OPEN',
  FROZEN = 'FROZEN',
  CLOSED = 'CLOSED',
}

/**
 * @class AccountAggregate
 * @description This is the aggregate root for the Account domain. It encapsulates the state and business logic
 * for a financial account. State changes are not performed directly but by creating and applying domain events.
 * This ensures a complete, auditable history of every change (Event Sourcing).
 * All public methods are either commands that generate events or queries that return state.
 * @implements DDD Aggregate Root pattern
 */
export class AccountAggregate {
  /**
   * @property {string} id - The unique identifier for the account aggregate (UUID).
   * @public
   * @readonly
   */
  public readonly id: string;

  private ownerId!: string;
  private balance: number = 0;
  private status: AccountStatus = AccountStatus.PENDING;
  private currency!: string;
  private accountType!: string;

  /**
   * @property {number} version - The current version of the aggregate, incremented with each event.
   * Used for optimistic concurrency control.
   */
  private version: number = -1;

  /**
   * @property {IDomainEvent[]} _uncommittedEvents - A list of events that have been generated by business operations but not yet persisted.
   * @private
   */
  private readonly _uncommittedEvents: IDomainEvent[] = [];

  /**
   * @constructor
   * @description Constructs an instance of an AccountAggregate. The constructor should only establish its identity.
   * All other state is hydrated via events.
   * @param {string} id - The unique identifier for the account aggregate.
   */
  public constructor(id: string) {
    this.id = id;
  }

  /**
   * @method getUncommittedEvents
   * @description Retrieves the list of uncommitted domain events.
   * The repository is responsible for persisting these events and then clearing them from the aggregate.
   * @returns {IDomainEvent[]} An array of domain events that need to be persisted.
   */
  public getUncommittedEvents(): IDomainEvent[] {
    return this._uncommittedEvents;
  }

  /**
   * @method markEventsAsCommitted
   * @description Clears the list of uncommitted events. This should be called by the repository
   * after the events have been successfully persisted to the event store.
   */
  public markEventsAsCommitted(): void {
    this._uncommittedEvents.length = 0;
  }

  /**
   * @method loadFromHistory
   * @description Reconstitutes an Account aggregate from a history of its domain events.
   * This method is used by the repository to load an existing aggregate from the event store.
   * @param {IDomainEvent[]} history - An ordered array of domain events representing the aggregate's history.
   */
  public loadFromHistory(history: IDomainEvent[]): void {
    history.forEach(event => this.apply(event, false));
    this.version = history.length > 0 ? history[history.length - 1].version : -1;
  }

  /**
   * @method create
   * @description Command to create a new Account. This is the designated public entry point for instantiating a new account.
   * It ensures the aggregate is created in a valid state by applying the initial `AccountCreatedEvent`.
   * @param {string} ownerId - The ID of the customer owning the account.
   * @param {string} accountType - The type of account (e.g., 'CHECKING', 'SAVINGS').
   * @param {string} currency - The ISO 4217 currency code.
   * @param {number} [initialBalance=0] - The starting balance for the account. Defaults to 0.
   * @returns {void}
   * @throws {ValidationError} If the initial balance is negative.
   * @throws {DomainError} If the account has already been created.
   * @example
   * const account = new AccountAggregate('a-uuid-v4');
   * account.create('user-123', 'CHECKING', 'USD', 100.00);
   */
  public create(ownerId: string, accountType: string, currency: string, initialBalance: number = 0): void {
    if (this.status !== AccountStatus.PENDING || this.version !== -1) {
      throw new DomainError('Account has already been created.');
    }
    if (initialBalance < 0) {
      throw new ValidationError('Initial balance cannot be negative.');
    }

    const event = new AccountCreatedEvent(
      this.id,
      ownerId,
      accountType,
      currency,
      initialBalance,
      new Date(),
      this.version + 1,
    );
    this.apply(event, true);
  }

  /**
   * @method deposit
   * @description Deposits a specified amount of funds into the account.
   * @param {number} amount - The amount to deposit.
   * @returns {void}
   * @throws {DomainError} If the account is closed or frozen, as these states restrict transactions.
   * @throws {ValidationError} If the deposit amount is not a positive number.
   * @example
   * account.deposit(50.00);
   */
  public deposit(amount: number): void {
    if (this.status === AccountStatus.CLOSED) {
      throw new DomainError('Cannot deposit funds into a closed account.');
    }
    if (this.status === AccountStatus.FROZEN) {
      throw new DomainError('Cannot deposit funds into a frozen account.');
    }
    if (amount <= 0) {
      throw new ValidationError('Deposit amount must be positive.');
    }
    this.apply(new FundsDepositedEvent(this.id, amount, new Date(), this.version + 1), true);
  }

  /**
   * @method withdraw
   * @description Withdraws a specified amount of funds from the account.
   * @param {number} amount - The amount to withdraw.
   * @returns {void}
   * @throws {DomainError} If the account is closed, frozen, or has insufficient funds.
   * @throws {ValidationError} If the withdrawal amount is not a positive number.
   * @example
   * account.withdraw(25.00);
   */
  public withdraw(amount: number): void {
    if (this.status === AccountStatus.CLOSED) {
      throw new DomainError('Cannot withdraw funds from a closed account.');
    }
    if (this.status === AccountStatus.FROZEN) {
      throw new DomainError('Cannot withdraw funds from a frozen account.');
    }
    if (amount <= 0) {
      throw new ValidationError('Withdrawal amount must be positive.');
    }
    if (this.balance < amount) {
      throw new DomainError('Insufficient funds for withdrawal.');
    }
    this.apply(new FundsWithdrawnEvent(this.id, amount, new Date(), this.version + 1), true);
  }

  /**
   * @method freeze
   * @description Freezes the account, preventing deposits and withdrawals.
   * @returns {void}
   * @throws {DomainError} If the account is already closed or frozen.
   * @example
   * account.freeze();
   */
  public freeze(): void {
    if (this.status === AccountStatus.CLOSED) {
      throw new DomainError('Cannot freeze a closed account.');
    }
    if (this.status === AccountStatus.FROZEN) {
      // Idempotent operation, no error thrown
      return;
    }
    this.apply(new AccountFrozenEvent(this.id, new Date(), this.version + 1), true);
  }

  /**
   * @method unfreeze
   * @description Unfreezes the account, re-enabling deposits and withdrawals.
   * @returns {void}
   * @throws {DomainError} If the account is not currently frozen.
   * @example
   * account.unfreeze();
   */
  public unfreeze(): void {
    if (this.status !== AccountStatus.FROZEN) {
      throw new DomainError('Account is not frozen.');
    }
    this.apply(new AccountUnfrozenEvent(this.id, new Date(), this.version + 1), true);
  }

  /**
   * @method close
   * @description Closes the account. This is a final, irreversible action.
   * @returns {void}
   * @throws {DomainError} If the account balance is not zero, to prevent loss of funds, or if the account is already closed.
   * @example
   * // Assuming balance is 0
   * account.close();
   */
  public close(): void {
    if (this.balance !== 0) {
      throw new DomainError('Cannot close an account with a non-zero balance.');
    }
    if (this.status === AccountStatus.CLOSED) {
      // Idempotent operation, no error thrown
      return;
    }
    this.apply(new AccountClosedEvent(this.id, new Date(), this.version + 1), true);
  }

  /**
   * @method apply
   * @description The core state mutation logic. It routes an event to the appropriate `on` method
   * to apply state changes and adds new events to the uncommitted list.
   * @param {IDomainEvent} event - The domain event to apply.
   * @param {boolean} isNew - Flag indicating if this is a new event (to be committed) or one from history (already committed).
   * @private
   */
  private apply(event: IDomainEvent, isNew: boolean): void {
    // This is a simple routing mechanism. A more robust implementation might use decorators or a map.
    switch (event.eventType) {
      case 'AccountCreatedEvent':
        this.onAccountCreated(event as AccountCreatedEvent);
        break;
      case 'FundsDepositedEvent':
        this.onFundsDeposited(event as FundsDepositedEvent);
        break;
      case 'FundsWithdrawnEvent':
        this.onFundsWithdrawn(event as FundsWithdrawnEvent);
        break;
      case 'AccountFrozenEvent':
        this.onAccountFrozen(event as AccountFrozenEvent);
        break;
      case 'AccountUnfrozenEvent':
        this.onAccountUnfrozen(event as AccountUnfrozenEvent);
        break;
      case 'AccountClosedEvent':
        this.onAccountClosed(event as AccountClosedEvent);
        break;
      default:
        throw new Error(`Unknown event type: ${event.eventType}`);
    }

    if (isNew) {
      this._uncommittedEvents.push(event);
      this.version = event.version;
    }
  }

  /**
   * @method onAccountCreated
   * @description State mutator for the AccountCreatedEvent. Initializes the aggregate's state.
   * @param {AccountCreatedEvent} event - The event data.
   * @private
   */
  private onAccountCreated(event: AccountCreatedEvent): void {
    this.ownerId = event.userId;
    this.balance = event.initialBalance;
    this.accountType = event.accountType;
    this.currency = event.currency;
    this.status = AccountStatus.OPEN;
  }

  /**
   * @method onFundsDeposited
   * @description State mutator for the FundsDepositedEvent. Increases the account balance.
   * @param {FundsDepositedEvent} event - The event data.
   * @private
   */
  private onFundsDeposited(event: FundsDepositedEvent): void {
    this.balance += event.amount;
  }

  /**
   * @method onFundsWithdrawn
   * @description State mutator for the FundsWithdrawnEvent. Decreases the account balance.
   * @param {FundsWithdrawnEvent} event - The event data.
   * @private
   */
  private onFundsWithdrawn(event: FundsWithdrawnEvent): void {
    this.balance -= event.amount;
  }

  /**
   * @method onAccountFrozen
   * @description State mutator for the AccountFrozenEvent. Sets the account status to FROZEN.
   * @param {AccountFrozenEvent} event - The event data.
   * @private
   */
  private onAccountFrozen(event: AccountFrozenEvent): void {
    this.status = AccountStatus.FROZEN;
  }

  /**
   * @method onAccountUnfrozen
   * @description State mutator for the AccountUnfrozenEvent. Sets the account status back to OPEN.
   * @param {AccountUnfrozenEvent} event - The event data.
   * @private
   */
  private onAccountUnfrozen(event: AccountUnfrozenEvent): void {
    this.status = AccountStatus.OPEN;
  }

  /**
   * @method onAccountClosed
   * @description State mutator for the AccountClosedEvent. Sets the account status to CLOSED.
   * @param {AccountClosedEvent} event - The event data.
   * @private
   */
  private onAccountClosed(event: AccountClosedEvent): void {
    this.status = AccountStatus.CLOSED;
  }
}
