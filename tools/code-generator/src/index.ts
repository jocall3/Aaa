/**
 * Generates a client-side TypeScript SDK for consuming the API, using Axios.
 */
class TypeScriptClientSDKGenerator implements ICodeGenerator {
    private readonly template: Handlebars.TemplateDelegate;

    constructor() {
        this.template = Handlebars.compile(`/**
 * @file Auto-generated by code-generator.
 * @version {{spec.info.version}}
 * @description Client SDK for the {{spec.info.title}} service.
 */

import axios, { AxiosInstance, AxiosRequestConfig } from 'axios';
import { {{dtoImports}} } from './dtos'; // Assuming DTOs are generated separately

/* eslint-disable */

/**
 * Configuration options for the API client.
 */
export interface ApiClientConfig {
    baseURL: string;
    accessToken?: string;
    timeout?: number;
}

/**
 * API Client for {{spec.info.title}}.
 * {{spec.info.description}}
 */
export class {{apiClassName}} {
    private client: AxiosInstance;

    /**
     * Creates an instance of the API client.
     * @param {ApiClientConfig} config - The configuration for the client.
     */
    constructor(config: ApiClientConfig) {
        this.client = axios.create({
            baseURL: config.baseURL,
            timeout: config.timeout || 10000,
            headers: {
                'Content-Type': 'application/json',
                ...(config.accessToken && { 'Authorization': 
                'Bearer ' + config.accessToken }),
            },
        });
    }

    {{#each operations}}
    /**
     * {{this.summary}}
     * {{this.description}}
     * @param { {{this.paramType}} } params - The request parameters.
     * @param {AxiosRequestConfig} [options] - Optional Axios request configuration overrides.
     * @returns {Promise<{{this.responseType}}>} The response data.
     */
    public async {{this.name}}(params: {{this.paramType}}, options?: AxiosRequestConfig): Promise<{{this.responseType}}> {
        const response = await this.client.{{this.method}}(
            '{{this.pathTemplate}}',
            {{this.bodyParam}}
            {
                ...options,
                params: {{this.queryParam}},
            }
        );
        return response.data;
    }
    {{/each}}
}
`);
    }

    public async generate(spec: OpenAPI.Document, outputDir: string): Promise<void> {
        const specV3 = spec as OpenAPIV3.Document;
        const operations: any[] = [];
        const dtoNames = new Set<string>();

        for (const p in specV3.paths) {
            const pathItem = specV3.paths[p]!;
            for (const method in pathItem) {
                if (['get', 'post', 'put', 'delete', 'patch'].includes(method)) {
                    const op = pathItem[method as OpenAPIV3.HttpMethods] as OpenAPIV3.OperationObject;
                    if (op.operationId) {
                        let responseType = 'void';
                        const successResponseKey = Object.keys(op.responses).find(k => k.startsWith('2'));
                        if (successResponseKey) {
                          const successResponse = op.responses[successResponseKey] as OpenAPIV3.ResponseObject;
                          if (successResponse.content?.['application/json']?.schema) {
                              responseType = this.toTsType(successResponse.content['application/json'].schema);
                              if (!['string', 'number', 'boolean', 'any', 'void'].includes(responseType) && !responseType.endsWith('[]')) dtoNames.add(responseType);
                          }
                        }

                        const paramList = (op.parameters as OpenAPIV3.ParameterObject[] || []);
                        const bodyParam = (method === 'post' || method === 'put' || method === 'patch') ? 'params.body,' : '';
                        const queryParam = (method === 'get') ? 'params.queryParams' : 'undefined';
                        const pathTemplate = p.replace(/{/g, '${params.pathParams.').replace(/}/g, '}');

                        operations.push({
                            name: op.operationId,
                            summary: op.summary,
                            description: op.description,
                            paramType: '{ [key: string]: any }', // Simplified
                            responseType,
                            method: method.toLowerCase(),
                            pathTemplate,
                            bodyParam,
                            queryParam
                        });
                    }
                }
            }
        }

        const content = this.template({
            spec,
            apiClassName: `${pascalCase(spec.info.title)}Client`,
            operations,
            dtoImports: Array.from(dtoNames).join(', ')
        });
        
        await fs.writeFile(path.join(outputDir, 'sdk.ts'), content);
        console.log(`Generated client-sdk/sdk.ts`);
    }

    private toTsType(schema: OpenAPIV3.SchemaObject | OpenAPIV3.ReferenceObject | undefined): string {
      if (!schema) return 'any';
      if ('$ref' in schema) {
        return pascalCase(schema.$ref.split('/').pop() || 'any');
      }
      switch (schema.type) {
        case 'string': return 'string';
        case 'number':
        case 'integer': return 'number';
        case 'boolean': return 'boolean';
        case 'array': return `${this.toTsType(schema.items)}[]`;
        case 'object': return 'Record<string, any>';
        default: return 'any';
      }
    }
}


// --- Main Application ---

/**
 * A map of available code generators, indexed by their target key.
 */
const generators: { [key: string]: ICodeGenerator } = {
  'typescript-server': new TypeScriptServerGenerator(),
  'typescript-client': new TypeScriptClientSDKGenerator(),
};

/**
 * The main function to run the code generator CLI.
 * It parses command-line arguments, validates the OpenAPI spec, and invokes the appropriate generator.
 */
async function main(): Promise<void> {
  const program = new Command();

  program
    .version('1.0.0')
    .description('In-house code generation framework for microservices based on OpenAPI specs.')
    .requiredOption('-i, --input <file>', 'Path to the OpenAPI v3 specification file (YAML or JSON)')
    .requiredOption('-o, --output <dir>', 'Output directory for the generated code')
    .requiredOption('-t, --target <target>', `Target for code generation. Supported: ${Object.keys(generators).join(', ')}`);

  program.parse(process.argv);
  const options = program.opts();

  console.log('🚀 Starting code generation process...');
  console.log(`   Input spec: ${options.input}`);
  console.log(`   Output directory: ${options.output}`);
  console.log(`   Target: ${options.target}`);

  try {
    await fs.ensureDir(options.output);

    console.log('🔍 Parsing and validating OpenAPI specification...');
    const spec = await SwaggerParser.bundle(options.input).then(api => SwaggerParser.validate(api)) as OpenAPI.Document;
    console.log(`✅ Specification for "${spec.info.title}" (v${spec.info.version}) parsed successfully.`);

    const generator = generators[options.target];
    if (!generator) {
      throw new Error(`Unsupported target "${options.target}". Supported targets are: ${Object.keys(generators).join(', ')}`);
    }

    console.log(`
🔥 Generating code for target '${options.target}'...`);
    await generator.generate(spec, options.output);
    console.log('\n✨ Code generation completed successfully.');

  } catch (err: any) {
    console.error('\n❌ An error occurred during code generation:');
    console.error(err.message);
    // For validation errors from swagger-parser
    if (err.details) {
        console.error('Details:', JSON.stringify(err.details, null, 2));
    }
    process.exit(1);
  }
}

// Execute main function
main();
